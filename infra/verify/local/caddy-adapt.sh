#!/usr/bin/env bash
# Validates infra/caddy/Caddyfile with Caddy 2.11.9 and regenerates infra/caddy/adapted.test.json,
# the adapted JSON that infra/verify/src/caddyfile.test.ts asserts on (run by `pnpm test`). The
# JSON records the Caddyfile's SHA-256, so the test fails when the Caddyfile changed and this
# script was not run again.
#
#   infra/verify/local/caddy-adapt.sh            validate + regenerate
#   infra/verify/local/caddy-adapt.sh --check    validate + fail when the committed JSON is stale
#
# Test values only (example.test, documentation addresses).
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO=$(cd "$HERE/../../.." && pwd)
# shellcheck source=infra/verify/local/lib.sh
. "$HERE/lib.sh"
IMAGE=docker.io/library/caddy:2.11.9@sha256:e40b94d0a43b5ff69cb20568d73f10c70703df7b0ffc2298eb3d723cdc9d0bd1
ENV_ARGS=(-e DOMAIN=example.test -e ACME_EMAIL=ops@example.test -e "ADMIN_ALLOWED_CIDRS=192.0.2.0/24 2001:db8::/32"
  -e "GLITCHTIP_ALLOWED_CIDRS=198.51.100.20/32" -e "WAHA_ALLOWED_CIDRS=198.51.100.30/32")
caddy_run() { docker run --rm "${ENV_ARGS[@]}" -v "$(host_path "$REPO/infra/caddy"):/etc/caddy:ro" "$IMAGE" caddy "$@"; }

if ! validation=$(caddy_run validate --config /etc/caddy/Caddyfile --adapter caddyfile 2>&1); then
  grep -E 'Error|error' <<<"$validation" | tail -3
  exit 1
fi
grep -o 'Valid configuration' <<<"$validation"
adapted=$(caddy_run adapt --config /etc/caddy/Caddyfile --adapter caddyfile 2>/dev/null)
# A Caddyfile that formats differently from `caddy fmt` is reported by adapt as a warning.
caddy_run fmt /etc/caddy/Caddyfile | diff -q - "$REPO/infra/caddy/Caddyfile" >/dev/null || {
  printf 'infra/caddy/Caddyfile is not caddy-fmt formatted\n'
  exit 1
}
target=$REPO/infra/caddy/adapted.test.json
generated=$(printf '%s' "$adapted" | node -e '
const { createHash } = require("node:crypto");
const { readFileSync } = require("node:fs");
const caddyfile = readFileSync(process.argv[1]);
const config = JSON.parse(readFileSync(0, "utf8"));
const out = {
  _comment: "Generated by infra/verify/local/caddy-adapt.sh from infra/caddy/Caddyfile with test values; do not edit.",
  caddyfileSha256: createHash("sha256").update(caddyfile).digest("hex"),
  env: { DOMAIN: "example.test", ACME_EMAIL: "ops@example.test", ADMIN_ALLOWED_CIDRS: "192.0.2.0/24 2001:db8::/32", GLITCHTIP_ALLOWED_CIDRS: "198.51.100.20/32", WAHA_ALLOWED_CIDRS: "198.51.100.30/32" },
  config,
};
process.stdout.write(JSON.stringify(out, null, 2) + "\n");
' "$(host_path "$REPO/infra/caddy")/Caddyfile")
if [[ ${1:-} == --check ]]; then
  diff -q <(printf '%s\n' "$generated") "$target" >/dev/null || {
    printf '%s is stale: run infra/verify/local/caddy-adapt.sh\n' "$target"
    exit 1
  }
  printf 'adapted JSON up to date\n'
else
  printf '%s\n' "$generated" >"$target"
  printf 'wrote %s\n' "$target"
fi
